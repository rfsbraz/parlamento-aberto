select
    cast(cast(Id as double) as bigint) as intervention_id,
    cast(Sessao as integer) as session_number,
    cast(DataReuniaoPlenaria as date) as meeting_date,
    TipoIntervencao as intervention_type,
    FaseSessao as session_phase,
    cast(cast(IdDebate as double) as bigint) as debate_id,
    Debate as debate,
    FaseDebate as debate_phase,
    cast(cast(ActividadeId as double) as bigint) as activity_id,
    Sumario as summary,
    Resumo as abstract,
    cast(cast(Deputados.idCadastro as double) as bigint) as cadastro_id,
    Deputados.nome as speaker_name,
    Deputados.GP as group_acronym,
    Qualidade as speaker_role,
    MembrosGoverno.nome as government_member_name,
    MembrosGoverno.cargo as government_member_role,
    MembrosGoverno.governo as government,
    Convidados.nome as guest_name,
    Convidados.cargo as guest_role,
    len(Publicacao) as publication_count,
    Publicacao[1].pubTipo as publication_type,
    cast(Publicacao[1].pubNr as integer) as publication_number,
    cast(Publicacao[1].pubdt as date) as publication_date,
    Publicacao[1].pag as pages,
    Publicacao[1].URLDiario as diary_url,
    {legislature} as legislature,
    {source_file} as source_file
from read_json(
    '{data_dir}/intervencoes/*/records*.ndjson',
    format = 'newline_delimited',
    filename = true,
    maximum_object_size = 100000000,
    columns = {
        Id: 'VARCHAR',
        Sessao: 'VARCHAR',
        DataReuniaoPlenaria: 'VARCHAR',
        TipoIntervencao: 'VARCHAR',
        FaseSessao: 'VARCHAR',
        IdDebate: 'VARCHAR',
        Debate: 'VARCHAR',
        FaseDebate: 'VARCHAR',
        ActividadeId: 'VARCHAR',
        Sumario: 'VARCHAR',
        Resumo: 'VARCHAR',
        Deputados: 'STRUCT(idCadastro VARCHAR, nome VARCHAR, GP VARCHAR)',
        Qualidade: 'VARCHAR',
        MembrosGoverno: 'STRUCT(nome VARCHAR, cargo VARCHAR, governo VARCHAR)',
        Convidados: 'STRUCT(nome VARCHAR, cargo VARCHAR)',
        Publicacao: 'STRUCT(pubTipo VARCHAR, pubNr VARCHAR, pubdt VARCHAR, pag VARCHAR[], URLDiario VARCHAR)[]'
    }
)
